// ---- 8. Zoom extreme test (standalone computation) ----
console.log('\n--- CRITERION 7: Zoom extremes (0.4 and 1.6) ---');

// Simulate zoomTree behavior
let TREE_SCALE = 1;

function simulateZoomTree(delta) {
  const next = delta === 0 ? 1 : Math.min(1.6, Math.max(0.4, TREE_SCALE + delta));
  TREE_SCALE = next;
  return TREE_SCALE;
}

// Test zoom in to max
TREE_SCALE = 1;
for (let i = 0; i < 20; i++) simulateZoomTree(0.1);
console.log('After 20 zoom-ins from 1.0:', TREE_SCALE, '(expected 1.6)');
const zoomInMax = TREE_SCALE === 1.6;

// Test zoom out to min
TREE_SCALE = 1;
for (let i = 0; i < 20; i++) simulateZoomTree(-0.1);
console.log('After 20 zoom-outs from 1.0:', TREE_SCALE, '(expected 0.4)');
const zoomOutMin = TREE_SCALE === 0.4;

// Test reset
TREE_SCALE = 1.5;
simulateZoomTree(0);
console.log('After reset from 1.5:', TREE_SCALE, '(expected 1)');
const zoomReset = TREE_SCALE === 1;

// Test boundary
TREE_SCALE = 0.4;
simulateZoomTree(-0.1);
console.log('Zoom out from 0.4:', TREE_SCALE, '(expected 0.4, clamped)');
const boundaryClamp = TREE_SCALE === 0.4;

TREE_SCALE = 1.6;
simulateZoomTree(0.1);
console.log('Zoom in from 1.6:', TREE_SCALE, '(expected 1.6, clamped)');
const boundaryClamp2 = TREE_SCALE === 1.6;

const zoomExtremesOk = zoomInMax && zoomOutMin && zoomReset && boundaryClamp && boundaryClamp2;
console.log('Zoom extremes criterion:', zoomExtremesOk ? 'PASS' : 'FAIL');

