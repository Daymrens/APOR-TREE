// Phase 3 verification: orthogonal connectors, branch palette colors, zoom/pan
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const htmlPath = path.resolve(__dirname, '../../../public/apor-family.html');
const html = fs.readFileSync(htmlPath, 'utf8');

console.log('=== PHASE 3 VERIFICATION ===');

// ---- 1. Extract script block for VM simulation ----
const scriptBlocks = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
const lastScript = scriptBlocks[scriptBlocks.length - 1][1];

// ---- 2. Orthogonal connector verification (source inspection) ----
console.log('\n--- CRITERION 1: Orthogonal connectors (no curved path commands) ---');

// Check that renderTree only uses M and L (line-to) commands, no C/Q/S/A (curves)
// Marriage: M ... L ... (horizontal)
const marriagePaths = html.match(/M \$\{A\.x \+ BOX_W\} \$\{y\} L \$\{B\.x\} \$\{y\}/);
console.log('Marriage edge uses M+L (horizontal):', !!marriagePaths);

// Parent drop: M ... L ... (vertical)
const parentDropPaths = html.match(/M \$\{pm\} \$\{py \+ BOX_H\} L \$\{pm\} \$\{busY\}/);
console.log('Parent drop edge uses M+L (vertical):', !!parentDropPaths);

// Bus: M ... L ... (horizontal)
const busPaths = html.match(/M \$\{Math\.min\(\.\.\.mids\)\} \$\{busY\} L \$\{Math\.max\(\.\.\.mids\)\} \$\{busY\}/);
console.log('Sibling bus uses M+L (horizontal):', !!busPaths);

// Sibling drops: M ... L ... (vertical)
const siblingDropPaths = html.match(/M \$\{mx\} \$\{busY\} L \$\{mx\} \$\{pos\[k\.id\]\.y\}/);
console.log('Sibling drops use M+L (vertical):', !!siblingDropPaths);

// Verify no curved path commands in renderTree's pathEl calls
// The pathEl function generates SVG path d attributes; check that the source
// only constructs paths with M and L (no C, Q, S, A)
const curvedPathPatterns = /\b[QqCcSsAa]\s/; // Curved SVG commands
const renderTreeSection = html.substring(html.indexOf('function renderTree()'), html.indexOf('function showDetail()'));
const pathConstructions = renderTreeSection.match(/pathEl\(`[^`]*`\)/g) || [];
console.log('Path construction calls found:', pathConstructions.length);

let curvedPathsFound = false;
for (const pc of pathConstructions) {
  if (curvedPathPatterns.test(pc)) {
    curvedPathsFound = true;
    console.log('  WARNING: Curved path found in:', pc.substring(0, 80));
  }
}
console.log('No curved path commands in edge generation:', !curvedPathsFound);

// Additional check: no C/Q/S/A in the path d strings generated by renderTree
// Scan for any path construction that might use curves
const allPathDs = renderTreeSection.match(/`M [^`]+`/g) || [];
let anyCurveInD = false;
for (const d of allPathDs) {
  if (/[QqCcSsAa]/.test(d.replace(/\$\{[^}]+\}/g, ''))) {
    anyCurveInD = true;
    console.log('  Curved command in d string:', d.substring(0, 80));
  }
}
console.log('All path d strings are rectilinear:', !anyCurveInD);

const orthogonalOk = !!marriagePaths && !!parentDropPaths && !!busPaths && !!siblingDropPaths && !curvedPathsFound && !anyCurveInD;
console.log('Orthogonal connectors criterion:', orthogonalOk ? 'PASS' : 'FAIL');

// ---- 3. Branch palette colors ----
console.log('\n--- CRITERION 2: Branch palette colors ---');

const expectedPalette = {
  'apor': '#2f6df6',
  'feliciano': '#16b364',
  'pedro': '#e8a63d',
  'presbitero': '#8b5cf6',
  'lumbab': '#ef4565',
};

let paletteOk = true;
for (const [branch, color] of Object.entries(expectedPalette)) {
  const cssRegex = new RegExp(`\\.br-${branch}\\s*\\{[^}]*fill:\\s*${color.replace('#', '#?')}`);
  // More flexible: check that .br-branch { ... fill: #color ... } exists
  const classDef = html.match(new RegExp(`\\.br-${branch}\\s*\\{([^}]*)\\}`));
  if (classDef) {
    const hasColor = classDef[1].includes(color);
    console.log(`  .br-${branch}: fill=${color} present: ${hasColor}`);
    if (!hasColor) paletteOk = false;
  } else {
    console.log(`  .br-${branch}: CSS class NOT FOUND`);
    paletteOk = false;
  }
}

// Check that renderTree applies the branch class via strip element
const branchStripCode = html.includes("strip.setAttribute('class', 'br-' + m.branch.toLowerCase())");
console.log('Branch class applied to node strip:', branchStripCode);

const branchPaletteOk = paletteOk && branchStripCode;
console.log('Branch palette criterion:', branchPaletteOk ? 'PASS' : 'FAIL');

// ---- 4. Zoom clamping verification ----
console.log('\n--- CRITERION 3: Zoom clamps to [0.4, 1.6] ---');

// Source inspection: check the zoomTree function clamping logic
const zoomTreeFn = html.substring(html.indexOf('function zoomTree('), html.indexOf('function fitTree('));
const clampRegex = /Math\.min\(1\.6,\s*Math\.max\(0\.4,\s*TREE_SCALE \+ delta\)\)/;
const hasClamp = clampRegex.test(zoomTreeFn);
console.log('zoomTree has clamp [0.4, 1.6]:', hasClamp);

// Check reset case (delta === 0 goes to 1)
const resetCase = zoomTreeFn.includes('delta === 0 ? 1 :');
console.log('zoomTree reset (delta=0) sets scale to 1:', resetCase);

// Check fitTree also clamps
const fitTreeFn = html.substring(html.indexOf('function fitTree()'), html.indexOf('(function initPan()'));
const fitClamp = fitTreeFn.includes('Math.min(1.6, Math.max(0.4');
console.log('fitTree also clamps [0.4, 1.6]:', fitClamp);

const zoomOk = hasClamp && resetCase && fitClamp;
console.log('Zoom clamping criterion:', zoomOk ? 'PASS' : 'FAIL');

// ---- 5. Drag-to-pan verification ----
console.log('\n--- CRITERION 4: Drag pans the tree ---');

